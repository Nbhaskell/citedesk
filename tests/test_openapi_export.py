"""The OpenAPI file the web app's types are generated from stays in step with the API.

The types themselves (`web/src/api/schema.d.ts`) are generated by Node and checked in CI.
"""

import json
from pathlib import Path

import pytest

from tools import export_openapi

REGENERATE = r".\.venv\Scripts\python.exe -m tools.export_openapi"


def test_the_committed_openapi_file_is_current() -> None:
    committed = export_openapi.OPENAPI_FILE
    assert committed.exists(), f"missing {committed}; run: {REGENERATE}"
    assert committed.read_text(encoding="utf-8") == export_openapi.render(), (
        f"web/openapi.json is out of date with the API; run: {REGENERATE}"
    )


def test_the_export_is_stable_and_has_every_route() -> None:
    first, second = export_openapi.render(), export_openapi.render()
    assert first == second and first.endswith("\n")
    paths = json.loads(first)["paths"]
    for path in (
        "/api/inquiries",
        "/api/inquiries/{inquiry_id}",
        "/api/drafts/{draft_id}/approve",
        "/api/drafts/{draft_id}/redraft",
        "/api/inquiries/{inquiry_id}/reprocess",
        "/api/insights",
        "/api/status",
    ):
        assert path in paths


def test_the_export_does_not_depend_on_the_developers_settings(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    monkeypatch.setenv("CITEDESK_DB_PATH", str(tmp_path / "other.db"))
    monkeypatch.setenv("SYNTHETIC_DATA", "false")
    assert export_openapi.render() == export_openapi.OPENAPI_FILE.read_text(encoding="utf-8")
